# Faça um programa que peça a temperatura em graus Celsius, transforme e mostre em graus Fahrenheit.

tempC = float(input('Informe a temperatura em Graus Celsius:'))

tempF = (9 * tempC + 160)/ 5

print(f'A conversão foi de {tempC} graus celsius para {tempF} graus Fahrennheit')